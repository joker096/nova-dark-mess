/**
 * Nova bot gateway — L2/L3 transport (docs/bots-roadmap.md §B4).
 *
 * Runs a headless `P2PManager` as a regular chat participant so a bot can join
 * 1:1 and group chats over WebRTC DataChannel or the HTTP store-and-forward
 * relay. The gateway holds the bot's keypair on behalf of the owner and is
 * reachable via an optional HTTP surface (Phase B5).
 *
 * Usage:
 *   const gateway = new BotGateway({ identity, storage, signaling, relay });
 *   await gateway.initialize();
 *   gateway.onIncomingMessage((from, chatId, text) => { ... });
 *   await gateway.sendMessage(chatId, text);
 */

import {
  type PreKeyBundle,
  type UserIdentity,
} from '../../../src/lib/crypto/identity';
import { P2PManager } from '../../../src/lib/p2p/p2pManager';
import { P2PSignalingClient } from '../../../src/lib/p2p/signaling';
import { MeshRelay } from '../../../src/lib/p2p/relay';
import { HttpRelayTransport } from '../../../src/lib/p2p/httpRelay';
import {
  GroupChatManager,
  type GroupPayload,
} from '../../../src/lib/p2p/groupManager';
import {
  isGroupMessageAllowed,
  parseGroupEnvelope,
  wrapGroupPayload,
} from '../../../src/lib/p2p/groupWire';
import { BotHTTPGateway } from './http';

export interface BotGatewayOptions {
  /** Bot's own identity (keypair generated by the owner). */
  identity: UserIdentity;
  /** Persistent storage for sessions and prekeys. */
  storage?: P2PManagerStorage;
  /** Signaling client (defaults to local BroadcastChannel). */
  signaling?: P2PSignalingClient;
  /** Mesh relay for store-and-forward fallback. */
  relay?: MeshRelay;
  /** HTTP relay transport for when no direct peers are online. */
  httpRelay?: HttpRelayTransport;
  /** Bot id used for group mention matching (defaults to `identity.fingerprint`). */
  botId?: string;
  /** Group privacy mode: when true only commands and mentions reach the bot. */
  mentionOnly?: boolean;
  /** Called when an encrypted 1:1 message arrives from a peer. */
  onMessage?: (fromFingerprint: string, chatId: string, plaintext: string) => void;
  /** Called when a group message arrives. */
  onGroupMessage?: (groupId: string, senderFingerprint: string, plaintext: string) => void;
  /** Called with join requests the bot must approve/reject (group privacy). */
  onGroupJoinRequest?: (groupId: string, fingerprint: string, name?: string) => void;
  onError?: (error: Error, peerFingerprint?: string) => void;
  /** Optional HTTP surface (Phase B5). Incoming P2P messages are enqueued here
   *  so they are reachable via getUpdates long-poll and webhook delivery. */
  httpGateway?: BotHTTPGateway;
}

interface P2PManagerStorage {
  loadPreKeyStore<T>(owner: string): Promise<T | null>;
  savePreKeyStore(owner: string, store: unknown): Promise<void>;
  loadSession<T>(chatId: string): Promise<T | null>;
  saveSession(chatId: string, session: unknown): Promise<void>;
}

/** Telegram-shaped HTTP surface (Phase B5). Re-exported so consumers can run
 *  it alongside BotGateway to expose /bot<token>/sendMessage, getUpdates,
 *  setWebhook, etc. */
export { BotHTTPGateway, validateWebhookUrl } from './http';

/** Public surface the gateway exposes over HTTP (Phase B5). */
export interface BotGatewayAPI {
  sendMessage(chatId: string, text: string): Promise<boolean>;
  getPreKeyBundle(): Promise<PreKeyBundle>;
  registerPeerBundle(fingerprint: string, bundle: PreKeyBundle): boolean;
}

export class BotGateway implements BotGatewayAPI {
  private readonly p2p: P2PManager;
  private initialized = false;
  private readonly groups = new Map<string, GroupChatManager>();

  constructor(private readonly options: BotGatewayOptions) {
    const signaling = options.signaling ?? new P2PSignalingClient();
    const relay = options.relay ?? new MeshRelay(options.identity.fingerprint);

    this.p2p = new P2PManager({
      identity: options.identity,
      signaling,
      storage: options.storage,
      relay,
      onMessage: (fromFingerprint, plaintext) => {
        const groupPayload = parseGroupEnvelope(plaintext);
        if (groupPayload) {
          void this.handleGroupFrame(fromFingerprint, groupPayload);
          return;
        }
        void options.onMessage?.(fromFingerprint, '', plaintext);
        // Enqueue incoming P2P messages into the HTTP surface so they are
        // reachable via getUpdates long-poll and webhook delivery (Phase B5).
        options.httpGateway?.enqueueIncoming(fromFingerprint, plaintext);
      },
      onPeerStateChange: () => void 0,
      onError: options.onError,
    });
  }

  /**
   * Route a group frame to the bot's group manager. Privacy mode is enforced
   * here, before the frame is decrypted into an update for the bot, and the
   * plaintext is handed to `onGroupMessage` only when it passes.
   */
  private async handleGroupFrame(fromFingerprint: string, payload: GroupPayload): Promise<void> {
    const manager = this.groups.get(payload.groupId);
    if (!manager) {
      this.options.onError?.(
        new Error(`No joined group ${payload.groupId}`),
        fromFingerprint,
      );
      return;
    }
    await manager.handleIncoming(fromFingerprint, payload);
  }

  /** Initialize prekeys and start listening for signaling/relay traffic. */
  public async initialize(): Promise<void> {
    if (this.initialized) return;
    await this.p2p.initialize();
    this.initialized = true;
  }

  /** The bot's fingerprint (its address on the mesh). */
  public get fingerprint(): string {
    return this.options.identity.fingerprint;
  }

  /** Export the bot's current prekey bundle so peers can start sessions with it. */
  public async getPreKeyBundle(): Promise<PreKeyBundle> {
    await this.p2p.initialize();
    const bundle = await this.p2p.getPreKeyBundle();
    return bundle;
  }

  /** Bot id used for mention matching in group privacy mode. */
  public get botId(): string {
    return this.options.botId ?? this.options.identity.fingerprint;
  }

  /** Register a peer's prekey bundle so the bot can start a session with them. */
  public registerPeerBundle(fingerprint: string, bundle: PreKeyBundle): boolean {
    return this.p2p.registerPeerBundle(fingerprint, bundle);
  }

  /** Send an encrypted 1:1 message to a peer. */
  public async sendMessage(chatId: string, text: string): Promise<boolean> {
    await this.p2p.initialize();
    return this.p2p.sendMessage(chatId, text);
  }

  /**
   * Join (or reconfigure) a group as the bot. The initial sender key is
   * distributed by default; pass `distribute: false` when the other members
   * have not joined yet and call `distributeGroupKey()` afterwards.
   */
  public async joinGroup(
    groupId: string,
    members: string[],
    opts?: { distribute?: boolean },
  ): Promise<void> {
    await this.initialize();
    let manager = this.groups.get(groupId);
    if (!manager) {
      manager = new GroupChatManager({
        groupId,
        localFingerprint: this.fingerprint,
        members,
        sendToPeer: (peer, payload) => this.sendGroupPayload(peer, payload),
        onMessage: (senderFingerprint, plaintext) => {
          if (this.options.mentionOnly && !isGroupMessageAllowed(plaintext, this.botId)) return;
          void this.options.onGroupMessage?.(groupId, senderFingerprint, plaintext);
        },
        onJoinRequest: (senderFingerprint, request) => {
          void this.options.onGroupJoinRequest?.(
            groupId,
            request.fingerprint,
            request.name,
          );
        },
        onError: (error, peer) => this.options.onError?.(error, peer),
      });
      this.groups.set(groupId, manager);
    } else {
      manager.setMembers(members);
    }
    await manager.initialize(opts?.distribute ?? true);
  }

  /** Re-send the bot's current sender key to every member (e.g. after they join). */
  public async distributeGroupKey(groupId: string): Promise<void> {
    const manager = this.groups.get(groupId);
    if (!manager) throw new Error(`Not in group ${groupId}`);
    await manager.distributeSenderKey();
  }

  /** Rotate the sender key after a member was removed. */
  public async rotateGroupKey(groupId: string): Promise<void> {
    const manager = this.groups.get(groupId);
    if (!manager) throw new Error(`Not in group ${groupId}`);
    await manager.rotateSenderKey();
  }

  /** Encrypt and fan a message out to the group's other members. */
  public async sendGroupMessage(groupId: string, text: string): Promise<boolean> {
    const manager = this.groups.get(groupId);
    if (!manager) throw new Error(`Not in group ${groupId}`);
    return manager.sendText(text);
  }

  public async addGroupMember(groupId: string, member: string): Promise<void> {
    const manager = this.groups.get(groupId);
    if (!manager) throw new Error(`Not in group ${groupId}`);
    await manager.addMember(member);
  }

  /** Removes a member and rotates the bot's sender key so they cannot read new messages. */
  public async removeGroupMember(groupId: string, member: string): Promise<void> {
    const manager = this.groups.get(groupId);
    if (!manager) throw new Error(`Not in group ${groupId}`);
    await manager.removeMember(member);
  }

  public async leaveGroup(groupId: string): Promise<void> {
    this.groups.delete(groupId);
  }

  public getJoinedGroups(): string[] {
    return [...this.groups.keys()];
  }

  /** Member roster of a joined group (read-only copy). */
  public getGroupMembers(groupId: string): string[] | null {
    return this.groups.get(groupId)?.getMembers() ?? null;
  }

  /**
   * Send an already-built group frame straight to one 1:1 peer. Used when the
   * client asks the bot to distribute its sender key or answer a join request
   * for a peer that is not yet in the bot's roster, and by tests to drive the
   * wire format directly.
   */
  public async sendGroupPayloadTo(peer: string, payload: GroupPayload): Promise<void> {
    if (!peer) throw new Error('Group payload target is empty');
    await this.sendGroupPayload(peer, payload);
  }

  /** Group privacy mode currently in effect for this bot. */
  public get groupPrivacy(): 'mention_only' | 'all' {
    return this.options.mentionOnly ? 'mention_only' : 'all';
  }

  private async sendGroupPayload(peer: string, payload: GroupPayload): Promise<void> {
    if (!peer) return;
    const ok = await this.p2p.sendMessage(peer, wrapGroupPayload(payload));
    if (!ok) throw new Error(`Group payload not delivered to ${peer}`);
  }

  public close(): void {
    this.groups.clear();
    this.p2p.close();
  }
}
