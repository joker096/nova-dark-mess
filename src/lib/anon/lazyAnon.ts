// Lazy-loaded anon module - heavy imports only loaded when anon features are used.
// Type-only exports (AnonCallSnapshot, Contact, FileEnvelope, ...) can't be part of the
// returned object, so import them directly from the modules below with `import type`.
export const loadAnonModules = async () => {
  const [
    { AnonCallSession },
    { parseAnonCallMessage },
    { decodeInvite, encodeInvite, isAllowedRelayUrl, isAnonInvite },
    { ackInboxPackets, contactFromOffer, createInvitation, inviteFromInbox, prepareInvitationAcceptance, receiveInboxPackets, contactIdentity, failoverInbox, migrateInbox, isBlockedContact, sendContactOffer, sendContactMessage },
    { queueSigningPublicKey },
    { createAnonTransport },
    { createAutoTransport, LocalAnonTransport },
    { createPushHintPoller, pushTokenForQueue, registerPush },
    { relayRateLimitRemainingMs },
    { checkTorRunning, isOnionUrl },
    { uint8ToBase64 },
    { assembleFile, createFileEnvelopes, parseFileEnvelope },
    { DEFAULT_QUEUE_ROTATION_MS, shouldRotateQueue },
    { noteRelayFailure, noteRelaySuccess, shouldFailoverRelay },
    { DummyTrafficScheduler },
    { planRelayEndpoints, relayEndpointsFromEnv: relayEndpointsFromEnvImport },
    { blockSender, createAbuseReportSubmission, isAbuseCategory, isBlocked, markAbuseReportUploaded, recordAbuseReport, unblockSender },
    { recordMessage, isRateLimited, getRateLimitStatus, blockSenderRateLimit, unblockSenderRateLimit, clearRateLimitData },
  ] = await Promise.all([
    import('./callSession'),
    import('./callProtocol'),
    import('./session'),
    import('./pairing'),
    import('./signing'),
    import('./transport'),
    import('./localTransport'),
    import('./push'),
    import('./httpRelay'),
    import('./tor'),
    import('./packet'),
    import('./fileTransfer'),
    import('./relays'),
    import('./relayHealth'),
    import('./jitter'),
    import('./relayEndpoints'),
    import('./blocks'),
    import('./rateLimit'),
  ]);

  return {
    AnonCallSession,
    parseAnonCallMessage,
    decodeInvite,
    encodeInvite,
    isAllowedRelayUrl,
    isAnonInvite,
    ackInboxPackets,
    contactFromOffer,
    createInvitation,
    inviteFromInbox,
    prepareInvitationAcceptance,
    receiveInboxPackets,
    contactIdentity,
    failoverInbox,
    migrateInbox,
    isBlockedContact,
    sendContactOffer,
    sendContactMessage,
    queueSigningPublicKey,
    createAnonTransport,
    createAutoTransport,
    LocalAnonTransport,
    createPushHintPoller,
    pushTokenForQueue,
    registerPush,
    relayRateLimitRemainingMs,
    checkTorRunning,
    isOnionUrl,
    uint8ToBase64,
    assembleFile,
    createFileEnvelopes,
    parseFileEnvelope,
    DEFAULT_QUEUE_ROTATION_MS,
    shouldRotateQueue,
    noteRelayFailure,
    noteRelaySuccess,
    shouldFailoverRelay,
    DummyTrafficScheduler,
    planRelayEndpoints,
    relayEndpointsFromEnv: relayEndpointsFromEnvImport,
    blockSender,
    createAbuseReportSubmission,
    isAbuseCategory,
    isBlocked,
    markAbuseReportUploaded,
    recordAbuseReport,
    unblockSender,
    recordMessage,
    isRateLimited,
    getRateLimitStatus,
    blockSenderRateLimit,
    unblockSenderRateLimit,
    clearRateLimitData,
  };
};